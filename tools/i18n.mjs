/**
 * i18n tooling (no WP-CLI needed):
 *  1. Extract t('…') strings from the admin TypeScript into
 *     gapban/includes/Admin/AdminStrings.php as __() calls, so one gettext
 *     catalogue covers PHP and JS.
 *  2. Build gapban/languages/gapban.pot from every __/_e/esc_html__/esc_attr__/
 *     esc_html_e/_x/_n call in the plugin PHP.
 *  3. Compile every gapban-*.po in gapban/languages to .mo.
 *
 *   node tools/i18n.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const walk = (dir, exts) =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? walk(p, exts) : exts.some((e) => p.endsWith(e)) ? [p] : [];
  });

/* 1. Admin strings ------------------------------------------------------- */
const adminStrings = new Set();
const T_RE = /\bt\(\s*'((?:[^'\\]|\\.)*)'/g;
for (const file of walk('src/admin', ['.ts', '.tsx'])) {
  const src = readFileSync(file, 'utf8');
  for (const m of src.matchAll(T_RE)) adminStrings.add(m[1].replace(/\\'/g, "'"));
}
const phpEsc = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const lines = [...adminStrings].sort().map((s) => {
  const ph = /%[sd]|%\d\$[sd]/.test(s) ? "\t\t\t/* translators: placeholders are filled in by the admin interface */\n" : '';
  return `${ph}\t\t\t'${phpEsc(s)}' => __( '${phpEsc(s)}', 'gapban' ),`;
});
writeFileSync(
  'gapban/includes/Admin/AdminStrings.php',
  `<?php
/**
 * Admin interface strings. GENERATED by tools/i18n.mjs from src/admin — do not edit.
 *
 * @package Gapban
 */

namespace Gapban\\Admin;

defined( 'ABSPATH' ) || exit;

final class AdminStrings {

	/**
	 * @return array<string, string> English source => translation
	 */
	public static function all(): array {
		return array(
${lines.join('\n')}
		);
	}
}
`,
);
console.log(`admin strings: ${adminStrings.size}`);

/* 2. POT ------------------------------------------------------------------ */
const entries = new Map(); // key: ctx\u0004msgid(\u0000plural) => refs
const add = (msgid, ref, ctx = '', plural = '') => {
  const key = (ctx ? ctx + '\u0004' : '') + msgid + (plural ? '\u0000' + plural : '');
  if (!entries.has(key)) entries.set(key, { msgid, ctx, plural, refs: [] });
  entries.get(key).refs.push(ref);
};
const unq = (s) => s.slice(1, -1).replace(/\\'/g, "'").replace(/\\\\/g, '\\');
const STR = "'(?:[^'\\\\]|\\\\.)*'";
const reSimple = new RegExp(`\\b(?:__|_e|esc_html__|esc_html_e|esc_attr__|esc_attr_e)\\(\\s*(${STR})\\s*,\\s*'gapban'`, 'g');
const reX = new RegExp(`\\b(?:_x|esc_html_x|esc_attr_x)\\(\\s*(${STR})\\s*,\\s*(${STR})\\s*,\\s*'gapban'`, 'g');
const reN = new RegExp(`\\b_n\\(\\s*(${STR})\\s*,\\s*(${STR})\\s*,[^,]+,\\s*'gapban'`, 'g');
for (const file of walk('gapban', ['.php'])) {
  const src = readFileSync(file, 'utf8');
  const rel = relative('gapban', file);
  const lineOf = (idx) => src.slice(0, idx).split('\n').length;
  for (const m of src.matchAll(reSimple)) add(unq(m[1]), `${rel}:${lineOf(m.index)}`);
  for (const m of src.matchAll(reX)) add(unq(m[1]), `${rel}:${lineOf(m.index)}`, unq(m[2]));
  for (const m of src.matchAll(reN)) add(unq(m[1]), `${rel}:${lineOf(m.index)}`, '', unq(m[2]));
}
const poStr = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n') + '"';
let pot = `# Copyright (C) Gapban
# This file is distributed under the GPL-2.0-or-later.
msgid ""
msgstr ""
"Project-Id-Version: Gapban 1.0.0\\n"
"MIME-Version: 1.0\\n"
"Content-Type: text/plain; charset=UTF-8\\n"
"Content-Transfer-Encoding: 8bit\\n"
"X-Domain: gapban\\n"

`;
for (const e of entries.values()) {
  pot += e.refs.slice(0, 5).map((r) => `#: ${r}`).join('\n') + '\n';
  if (/%[sd]|%\d\$[sd]/.test(e.msgid)) pot += '#, php-format\n';
  if (e.ctx) pot += `msgctxt ${poStr(e.ctx)}\n`;
  pot += `msgid ${poStr(e.msgid)}\n`;
  if (e.plural) pot += `msgid_plural ${poStr(e.plural)}\nmsgstr[0] ""\nmsgstr[1] ""\n\n`;
  else pot += 'msgstr ""\n\n';
}
writeFileSync('gapban/languages/gapban.pot', pot);
console.log(`pot entries: ${entries.size}`);

/* 3. PO → MO -------------------------------------------------------------- */
function parsePo(text) {
  // Entries are separated by blank lines; fields may continue on following "..." lines.
  const unpo = (q) => JSON.parse(q);
  return text
    .split(/\n\s*\n/)
    .map((block) => {
      const e = {};
      let field = null;
      for (const raw of block.split('\n')) {
        const line = raw.trim();
        if (!line || line.startsWith('#')) continue;
        const m = line.match(/^(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(".*")$/);
        if (m) {
          field = m[1];
          e[field] = unpo(m[2]);
        } else if (line.startsWith('"') && field) {
          e[field] += unpo(line);
        }
      }
      return e;
    })
    .filter((e) => e.msgid !== undefined);
}
function compileMo(entriesList) {
  const items = entriesList
    .filter((e) => e.msgid !== undefined && (e.msgstr || e['msgstr[0]']))
    .map((e) => {
      const key = (e.msgctxt ? e.msgctxt + '\u0004' : '') + e.msgid + (e.msgid_plural !== undefined ? '\u0000' + e.msgid_plural : '');
      const val = e.msgid_plural !== undefined ? Object.keys(e).filter((k) => k.startsWith('msgstr[')).sort().map((k) => e[k]).join('\u0000') : e.msgstr;
      return [Buffer.from(key, 'utf8'), Buffer.from(val, 'utf8')];
    })
    .sort((a, b) => Buffer.compare(a[0], b[0]));
  const n = items.length;
  const headerSize = 28;
  const keysOffset = headerSize;
  const valsOffset = keysOffset + n * 8;
  let dataOffset = valsOffset + n * 8;
  const keyTable = Buffer.alloc(n * 8);
  const valTable = Buffer.alloc(n * 8);
  const chunks = [];
  items.forEach(([k], i) => {
    keyTable.writeUInt32LE(k.length, i * 8);
    keyTable.writeUInt32LE(dataOffset, i * 8 + 4);
    chunks.push(k, Buffer.from([0]));
    dataOffset += k.length + 1;
  });
  items.forEach(([, v], i) => {
    valTable.writeUInt32LE(v.length, i * 8);
    valTable.writeUInt32LE(dataOffset, i * 8 + 4);
    chunks.push(v, Buffer.from([0]));
    dataOffset += v.length + 1;
  });
  const header = Buffer.alloc(headerSize);
  header.writeUInt32LE(0x950412de, 0);
  header.writeUInt32LE(0, 4);
  header.writeUInt32LE(n, 8);
  header.writeUInt32LE(keysOffset, 12);
  header.writeUInt32LE(valsOffset, 16);
  header.writeUInt32LE(0, 20);
  header.writeUInt32LE(dataOffset, 24);
  return Buffer.concat([header, keyTable, valTable, ...chunks]);
}
for (const f of readdirSync('gapban/languages').filter((f) => f.endsWith('.po'))) {
  const list = parsePo(readFileSync(join('gapban/languages', f), 'utf8'));
  const mo = compileMo(list);
  writeFileSync(join('gapban/languages', f.replace(/\.po$/, '.mo')), mo);
  const translated = list.filter((e) => e.msgid && (e.msgstr || e['msgstr[0]'])).length;
  const missing = [...entries.values()].filter((e) => !list.some((x) => x.msgid === e.msgid && (x.msgstr || x['msgstr[0]'])));
  console.log(`${f}: ${translated} translated, ${missing.length} missing`);
  if (missing.length && process.argv.includes('--missing')) missing.forEach((m) => console.log('  MISSING: ' + m.msgid));
}
