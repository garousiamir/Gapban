"""Original soundtrack + sound effects for the Gapban promo, synthesized from scratch.

Everything here is generated by code (no samples, no third-party music), so the
result is original and free of licensing restrictions.

    python3 marketing/promo/audio.py out.wav

Track: 128 BPM energetic electronic pop in A minor (Am–F–C–G), sidechained
pads and bass, plucky arpeggio, four-on-the-floor drums, risers and impacts
aligned to the video's scene cuts, UI sound effects from timeline.json.
"""
import json
import sys
import wave

import numpy as np
from scipy.signal import butter, sosfilt, sosfiltfilt

SR = 44100
TL = json.load(open('marketing/promo/timeline.json'))
DUR = TL['duration']
BPM = TL['bpm']
BEAT = 60 / BPM
N = int(SR * (DUR + 0.5))
rng = np.random.default_rng(7)

music = np.zeros((N, 2))
sfx = np.zeros((N, 2))
kick_env = np.zeros(N)  # for sidechain


def t_(n):
    return np.arange(n) / SR


def add(buf, start, sig, gain=1.0, pan=0.0):
    i = int(start * SR)
    if i >= N:
        return
    if sig.ndim == 1:
        l, r = np.sqrt(0.5 * (1 - pan)), np.sqrt(0.5 * (1 + pan))
        sig = np.stack([sig * l * 1.414, sig * r * 1.414], axis=1)
    n = min(len(sig), N - i)
    buf[i:i + n] += sig[:n] * gain


def lp(x, f, order=2):
    return sosfilt(butter(order, min(f, SR / 2 - 100) / (SR / 2), 'low', output='sos'), x)


def hp(x, f, order=2):
    return sosfilt(butter(order, f / (SR / 2), 'high', output='sos'), x)


def bp(x, lo, hi):
    return sosfilt(butter(2, [lo / (SR / 2), hi / (SR / 2)], 'band', output='sos'), x)


def adsr(n, a=0.005, d=0.1, s=0.6, r=0.1):
    env = np.ones(n) * s
    na, nd, nr = int(a * SR), int(d * SR), int(r * SR)
    env[:na] = np.linspace(0, 1, na) if na else env[:na]
    env[na:na + nd] = np.linspace(1, s, len(env[na:na + nd]))
    if nr:
        env[-nr:] *= np.linspace(1, 0, nr)
    return env


def note_hz(midi):
    return 440.0 * 2 ** ((midi - 69) / 12)


def saw(freq, n, detune=0.0):
    t = t_(n)
    out = np.zeros(n)
    for d in (-detune, 0, detune) if detune else (0,):
        ph = (freq * (1 + d) * t) % 1.0
        out += 2 * ph - 1
    return out / (3 if detune else 1)


# ----------------------------------------------------------------- drums ----
def kick(level=1.0):
    n = int(0.42 * SR)
    t = t_(n)
    f = 48 + 110 * np.exp(-t * 32)
    ph = 2 * np.pi * np.cumsum(f) / SR
    body = np.sin(ph) * np.exp(-t * 7.5)
    click = rng.standard_normal(n) * np.exp(-t * 400) * 0.25
    return np.tanh((body + click) * 1.6) * level


def clap():
    n = int(0.3 * SR)
    t = t_(n)
    noise = bp(rng.standard_normal(n), 900, 6000)
    env = np.zeros(n)
    for o in (0, 0.011, 0.022):
        i = int(o * SR)
        env[i:] += np.exp(-(t[: n - i]) * 38)
    env += np.exp(-t * 9) * 0.25
    return noise * env * 0.5


def hat(open_=False):
    n = int((0.22 if open_ else 0.05) * SR)
    t = t_(n)
    x = hp(rng.standard_normal(n), 7500)
    return x * np.exp(-t * (14 if open_ else 70)) * (0.32 if open_ else 0.22)


def snare_roll(start, end):
    t = start
    k = 0
    while t < end:
        frac = (t - start) / (end - start)
        step = BEAT / (2 if frac < 0.4 else 4 if frac < 0.75 else 8)
        add(music, t, clap() * (0.35 + 0.65 * frac), 0.9)
        t += step
        k += 1


# ------------------------------------------------------------- harmony ----
# A minor: Am – F – C – G (one chord per bar, 4 beats).
CHORDS = [[57, 60, 64], [53, 57, 60], [48, 52, 55], [55, 59, 62]]
ROOTS = [45, 41, 48, 43]
BAR = BEAT * 4


def pad_chord(chord, n):
    sig = np.zeros(n)
    for m in chord + [chord[0] + 12]:
        sig += saw(note_hz(m), n, detune=0.006)
    sig = lp(sig, 2600)
    return sig * 0.09


def pluck(m, dur=0.22):
    n = int(dur * SR)
    t = t_(n)
    s = saw(note_hz(m), n, detune=0.004) + 0.5 * np.sin(2 * np.pi * note_hz(m + 12) * t)
    cutoff_env = np.exp(-t * 18)
    s = lp(s, 5000) * 0.6 + lp(s, 900) * 0.4
    return s * (0.15 + 0.85 * cutoff_env) * np.exp(-t * 9) * 0.22


def bass_note(m, dur):
    n = int(dur * SR)
    t = t_(n)
    s = saw(note_hz(m), n) * 0.6 + np.sin(2 * np.pi * note_hz(m) * t)
    return lp(s, 420) * adsr(n, 0.004, 0.08, 0.7, 0.03) * 0.42


def section_level(t):
    """Arrangement: intro (sparse) → main → build → drop → outro."""
    if t < 1.1:
        return 'riser'
    if t < 3.75:
        return 'intro'
    if t < 34.1:
        return 'main'
    if t < 35.625:
        return 'build'
    return 'drop'


bars = int(np.ceil(DUR / BAR)) + 1
for b in range(bars):
    bar_t = b * BAR
    if bar_t >= DUR:
        break
    ci = b % 4
    sec = section_level(bar_t + 0.01)
    # Pads every bar from the intro on.
    if sec != 'riser':
        n = int(BAR * SR)
        add(music, bar_t, pad_chord(CHORDS[ci], n) * (0.7 if sec == 'intro' else 1.0), 1.0, 0.0)
    for beat in range(4):
        t = bar_t + beat * BEAT
        s = section_level(t + 0.001)
        if t >= DUR:
            break
        if s in ('main', 'drop') or (s == 'intro' and t >= 1.1 and beat == 0):
            add(music, t, kick(), 0.95)
            kick_env[int(t * SR): int((t + 0.25) * SR)] = np.maximum(kick_env[int(t * SR): int((t + 0.25) * SR)], np.exp(-np.arange(min(int(0.25 * SR), N - int(t * SR))) / SR * 14)[: len(kick_env[int(t * SR): int((t + 0.25) * SR)])])
        if s in ('main', 'drop'):
            if beat in (1, 3):
                add(music, t, clap(), 0.75)
            add(music, t + BEAT / 2, hat(True), 0.7, 0.25)
            for k in range(4):
                add(music, t + k * BEAT / 4, hat(), 0.55 + 0.25 * (k % 2), -0.2)
            # Bass: off-beat pumping eighths.
            add(music, t + BEAT / 2, bass_note(ROOTS[ci] if beat < 3 or ci % 2 == 0 else ROOTS[ci] + 7, BEAT / 2 * 0.9), 1.0)
            add(music, t, bass_note(ROOTS[ci] - 12, BEAT / 2 * 0.8), 0.55)
        if s == 'intro':
            add(music, t + BEAT / 2, hat(), 0.6, 0.2)
        # Arpeggio 16ths (main and drop), up-down pattern over the chord.
        if s in ('intro', 'main', 'drop'):
            arp = CHORDS[ci] + [CHORDS[ci][0] + 12]
            pattern = [0, 1, 2, 3, 2, 1, 3, 1]
            for k in range(4):
                idx = pattern[(beat * 4 + k) % 8]
                gain = 0.7 if s == 'intro' else 1.0
                add(music, t + k * BEAT / 4, pluck(arp[idx] + 12), gain, (-0.35 if k % 2 else 0.35))

# Build: snare roll and filtered pads into the drop.
snare_roll(34.1, 35.55)

# Sidechain pumping on everything but drums is approximated by ducking the whole
# music bus slightly on each kick (drums dominate the transient anyway).
duck = 1 - 0.35 * kick_env[:N]
music *= duck[:, None]

# Lowpass sweep over the build (opens again at the drop).
b0, b1 = int(34.1 * SR), int(35.625 * SR)
seg = music[b0:b1].copy()
chunks = 12
for c in range(chunks):
    s0, s1 = c * len(seg) // chunks, (c + 1) * len(seg) // chunks
    f = 6000 * (1 - c / chunks) + 500
    seg[s0:s1] = sosfilt(butter(2, f / (SR / 2), 'low', output='sos'), seg[s0:s1], axis=0)
music[b0:b1] = seg

# Outro fade.
fade0 = int((DUR - 1.2) * SR)
music[fade0:] *= np.linspace(1, 0, N - fade0)[:, None] ** 1.5


# ------------------------------------------------------------------ SFX ----
def riser(dur):
    n = int(dur * SR)
    t = t_(n)
    noise = rng.standard_normal(n)
    out = np.zeros(n)
    steps = 24
    for c in range(steps):
        s0, s1 = c * n // steps, (c + 1) * n // steps
        f = 400 + (9000 - 400) * (c / steps) ** 2
        out[s0:s1] = bp(noise[s0:s1], f * 0.6, min(f * 1.4, 18000))
    tone = np.sin(2 * np.pi * np.cumsum(220 + 660 * (t / dur) ** 2) / SR) * 0.25
    return (out * 0.5 + tone) * (t / dur) ** 1.6 * 0.6


def impact():
    n = int(2.2 * SR)
    t = t_(n)
    sub = np.sin(2 * np.pi * np.cumsum(30 + 90 * np.exp(-t * 6)) / SR) * np.exp(-t * 2.2)
    crash = hp(rng.standard_normal(n), 3000) * np.exp(-t * 3) * 0.35
    boom = lp(rng.standard_normal(n), 300) * np.exp(-t * 5) * 1.2
    return np.tanh((sub + crash + boom) * 1.3) * 0.75


def whoosh(dur=0.55):
    n = int(dur * SR)
    t = t_(n)
    x = rng.standard_normal(n)
    out = np.zeros(n)
    steps = 16
    for c in range(steps):
        s0, s1 = c * n // steps, (c + 1) * n // steps
        f = 300 + 5000 * np.sin(np.pi * c / steps)
        out[s0:s1] = bp(x[s0:s1], max(f * 0.5, 100), min(f * 1.6, 18000))
    env = np.sin(np.pi * t / dur) ** 2
    pan = np.linspace(-0.8, 0.8, n)
    sig = out * env * 0.55
    return np.stack([sig * (1 - pan) / 1.4, sig * (1 + pan) / 1.4], axis=1)


def pop():
    n = int(0.16 * SR)
    t = t_(n)
    f = 950 * np.exp(-t * 18) + 280
    return np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 26) * 0.45


def click():
    n = int(0.03 * SR)
    t = t_(n)
    return hp(rng.standard_normal(n), 2000) * np.exp(-t * 250) * 0.5 + np.sin(2 * np.pi * 2200 * t) * np.exp(-t * 300) * 0.2


def swell():
    n = int(0.5 * SR)
    t = t_(n)
    s = np.sin(2 * np.pi * np.cumsum(500 + 700 * t / 0.5) / SR)
    return s * np.sin(np.pi * t / 0.5) * 0.18


def typing(dur):
    out = np.zeros(int(dur * SR) + SR // 10)
    t = 0.0
    while t < dur:
        n = int(0.025 * SR)
        k = hp(rng.standard_normal(n), 1500) * np.exp(-t_(n) * 260) * (0.18 + 0.1 * rng.random())
        i = int(t * SR)
        out[i:i + n] += k
        t += 0.06 + rng.random() * 0.07
    return out


def send():
    n = int(0.35 * SR)
    t = t_(n)
    chirp = np.sin(2 * np.pi * np.cumsum(600 + 2200 * (t / 0.35)) / SR) * np.exp(-t * 9) * 0.3
    return chirp + lp(rng.standard_normal(n), 4000) * np.sin(np.pi * t / 0.35) * 0.12


def ding():
    n = int(1.2 * SR)
    t = t_(n)
    tone = (np.sin(2 * np.pi * 1318.5 * t) + 0.5 * np.sin(2 * np.pi * 2637 * t) + 0.25 * np.sin(2 * np.pi * 3955 * t)) * np.exp(-t * 4)
    tone2 = np.zeros(n)
    d = int(0.11 * SR)
    tone2[d:] = (np.sin(2 * np.pi * 1760 * t[: n - d]) + 0.4 * np.sin(2 * np.pi * 3520 * t[: n - d])) * np.exp(-t[: n - d] * 4)
    return (tone + tone2) * 0.16


def tick():
    n = int(0.05 * SR)
    t = t_(n)
    return np.sin(2 * np.pi * 3200 * t) * np.exp(-t * 120) * 0.22


def sparkle():
    out = np.zeros(int(1.5 * SR))
    for k in range(9):
        f = note_hz(rng.choice([81, 84, 88, 91, 93, 96]))
        n = int(0.6 * SR)
        t = t_(n)
        s = np.sin(2 * np.pi * f * t) * np.exp(-t * 7) * 0.08
        i = int(k * 0.09 * SR)
        out[i:i + n] += s
    return out


for ev in TL['sfx']:
    t, kind = ev['t'], ev['type']
    if kind == 'riser':
        add(sfx, t, riser(ev.get('dur', 1.0)), 1.0)
    elif kind == 'impact':
        add(sfx, t, impact(), 1.0)
    elif kind == 'whoosh':
        add(sfx, t - 0.1, whoosh(), 1.0)
    elif kind == 'pop':
        add(sfx, t, pop(), 1.0, rng.uniform(-0.4, 0.4))
    elif kind == 'click':
        add(sfx, t, click(), 1.0)
    elif kind == 'swell':
        add(sfx, t, swell(), 1.0)
    elif kind == 'typing':
        add(sfx, t, typing(ev.get('dur', 1.5)), 1.0, 0.15)
    elif kind == 'send':
        add(sfx, t, send(), 1.0)
    elif kind == 'ding':
        add(sfx, t, ding(), 1.0)
    elif kind == 'tick':
        add(sfx, t, tick(), 1.0, rng.uniform(-0.5, 0.5))
    elif kind == 'sparkle':
        add(sfx, t, sparkle(), 1.0, 0.2)

# ---------------------------------------------------------------- mix -----
# Simple stereo room on the music bus (short multi-tap delays).
room = np.zeros_like(music)
for d, g in ((0.031, 0.25), (0.047, 0.2), (0.071, 0.15), (0.113, 0.1)):
    k = int(d * SR)
    room[k:, 0] += music[:-k, 1] * g
    room[k:, 1] += music[:-k, 0] * g
mix = music * 0.85 + room * 0.35 + sfx * 1.1
mix = sosfiltfilt(butter(1, 25 / (SR / 2), 'high', output='sos'), mix, axis=0)

# Soft clip + normalise to about -1 dBFS peak.
mix = np.tanh(mix * 1.15)
mix = mix / np.max(np.abs(mix)) * 0.89
mix = mix[: int(DUR * SR)]
mix[-int(0.05 * SR):] *= np.linspace(1, 0, int(0.05 * SR))[:, None]

out = sys.argv[1] if len(sys.argv) > 1 else 'promo.wav'
pcm = (mix * 32767).astype('<i2')
with wave.open(out, 'wb') as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(SR)
    w.writeframes(pcm.tobytes())
print('wrote', out, f'{DUR}s')
